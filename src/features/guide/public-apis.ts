export type ApiCategoryId = (typeof API_CATEGORIES)[number]["id"];

export interface PublicApi {
  /** Stable slug, also used as the sample id in "Try it" links. */
  id: string;
  name: string;
  category: ApiCategoryId;
  description: string;
  baseUrl: string;
  docsUrl: string;
  apiKey: "none" | "optional";
  browserDirect: boolean;
  /** ISO date of the last manual check of the sample and documentation link. */
  lastChecked: string;
  sample: RequestConfig;
}

const CHECKED = "2026-11-28";

function rows(entries: Record<string, string>): KeyValueRow[] {
  return Object.entries(entries).map(([key, value]) => ({
    key,
    value,
    enabled: true,
  }));
}

function get(
  url: string,
  params: Record<string, string> = {},
  headers: Record<string, string> = {},
): RequestConfig {
  return {
    url,
    method: "GET",
    params: rows(params),
    headers: rows(headers),
    body: { type: "none", content: "" },
    strategy: "browser",
  };
}

function postJson(url: string, body: unknown): RequestConfig {
  return {
    url,
    method: "POST",
    params: [],
    headers: [],
    body: { type: "json", content: JSON.stringify(body, null, 2) },
    strategy: "browser",
  };
}

